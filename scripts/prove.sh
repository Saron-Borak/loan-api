#!/usr/bin/env bash
# Runs every proof from the Lesson 4.7 requirements table and writes the evidence to CHECKLIST.md.
# Usage (from the repository root, with Docker running):  bash scripts/prove.sh
set -u
OUT=CHECKLIST.md
run() {  # run a command, show it, and append "command + output" to the checklist
  echo "\$ $*" | tee -a "$OUT.tmp"
  bash -c "$*" 2>&1 | tee -a "$OUT.tmp"
  echo >> "$OUT.tmp"
}
section() { printf '\n## %s\n\n```text\n' "$1" >> "$OUT.tmp"; }
endsection() { printf '```\n' >> "$OUT.tmp"; [ -n "${1:-}" ] && printf '\n%s\n' "$1" >> "$OUT.tmp"; }

rm -f "$OUT.tmp"
printf '# CHECKLIST: loan-api production image\n\nEvidence for every requirement in the Lesson 4.7 table. Generated by `scripts/prove.sh` on %s.\n' "$(date -u '+%Y-%m-%d %H:%M UTC')" > "$OUT.tmp"

echo "== Building images =="
docker build -q -t loan-api:dev -f Dockerfile . >/dev/null
docker build -q -t loan-api:prod -f Dockerfile.prod . >/dev/null

section "1. Multi-stage Dockerfile.prod: slim base, non-root user, HEALTHCHECK"
run "grep -nE '^(FROM|USER|HEALTHCHECK)' Dockerfile.prod"
run "docker run --rm --entrypoint whoami loan-api:prod"
docker rm -f prove-health >/dev/null 2>&1
docker run -d --name prove-health -p 8001:8000 loan-api:prod >/dev/null
sleep 30
run "docker ps --filter name=prove-health --format '{{.Names}}  {{.Status}}'"
run "docker inspect --format '{{.State.Health.Status}}' prove-health"
docker rm -f prove-health >/dev/null
endsection "Two FROM lines (builder + python:3.12-slim runtime), USER appuser, and a HEALTHCHECK that calls /health. whoami prints appuser and the container reports (healthy)."

section "2. .dockerignore excludes Git, caches, local models and dev config"
run "cat .dockerignore"
endsection "Git (.git), caches (__pycache__, .pytest_cache, .venv), local models (model.joblib, models/) and dev config (.devcontainer, .vscode) are excluded."

section "3. Model path configurable with MODEL_PATH"
mkdir -p models
run "docker run --rm -v \"\$(pwd)/models:/out\" --entrypoint sh loan-api:dev -c 'python train.py --version 1.1.0 --out /out/model.joblib'"
docker rm -f prove-model >/dev/null 2>&1
docker run -d --name prove-model -p 8002:8000 -v "$(pwd)/models:/models:ro" -e MODEL_PATH=/models/model.joblib loan-api:prod >/dev/null
sleep 12
run "curl -s http://localhost:8002/health"
docker rm -f prove-model >/dev/null
endsection "The same image loads the mounted 1.1.0 model when MODEL_PATH=/models/model.joblib, without rebuilding."

section "4. compose.yaml runs API + PostgreSQL + Adminer, API built from Dockerfile.prod"
run "grep -n -A3 'build:' compose.yaml"
docker compose up -d --build >/dev/null 2>&1
sleep 40
run "docker compose ps"
run "curl -s http://localhost:8000/health"
run "curl -s -X POST http://localhost:8000/api/v1/predictions -H 'Content-Type: application/json' -d '{\"amount_usd\": 1500, \"term_months\": 12, \"monthly_income_usd\": 400, \"previous_loans\": 1, \"late_payments\": 0}'"
endsection "All three services are up; api and db show (healthy)."

section "5. Image at least 40% smaller than the full-Python variant"
run "docker images loan-api --format 'table {{.Repository}}:{{.Tag}}\t{{.Size}}'"
DEV=$(docker image inspect loan-api:dev --format '{{.Size}}'); PROD=$(docker image inspect loan-api:prod --format '{{.Size}}')
PCT=$(( 100 - PROD * 100 / DEV ))
endsection "loan-api:prod is ${PCT}% smaller than loan-api:dev (requirement: at least 40%)."

section "6. No HIGH or CRITICAL findings without a note"
run "docker run --rm -v /var/run/docker.sock:/var/run/docker.sock aquasec/trivy:0.69.3 image --quiet --severity HIGH,CRITICAL --ignore-unfixed loan-api:prod"
endsection "NOTES: (fill in) For each HIGH/CRITICAL finding above, write: rebuilt and fixed, or why it cannot be fixed yet. If the table is empty, write: No HIGH or CRITICAL findings with a fix available."

section "7. Image published as <your-name>/loan-api:1.0.0 and :latest"
endsection "Run scripts/publish.sh, then add the Docker Hub link here: https://hub.docker.com/r/<your-name>/loan-api/tags"

mv "$OUT.tmp" "$OUT"
echo; echo "== Wrote $OUT. Review section 6 notes, then commit and push. =="
